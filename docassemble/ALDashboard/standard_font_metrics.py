_CACHE: Dict[str, Dict[int, int]] = {}


def standard_14_widths(canonical_name: str) -> Optional[Dict[int, int]]:
    """Return published widths for a standard 14 face, keyed by code point."""
    cached = _CACHE.get(canonical_name)
    if cached is not None:
        return cached
    raw = _RAW_WIDTHS.get(canonical_name)
    if raw is None:
        return None
    default, listed = raw
    # A default of zero means the face is proportional and every measured
    # width is listed, so nothing is filled in that was never measured.
    table = {code: default for code in range(0x20, 0x100)} if default else {}
    for item in listed.split():
        code, _, width = item.partition(":")
        table[int(code)] = int(width)
    _CACHE[canonical_name] = table
    return table


def is_standard_14(canonical_name: str) -> bool:
    """Report whether this canonical name is one of the standard 14 faces."""
    return canonical_name in _RAW_WIDTHS


def is_unicode_keyed(canonical_name: str) -> bool:
    """Report whether this face's widths are keyed by Unicode code point.

    Every face but ZapfDingbats is; see the module docstring for why that one
    is keyed by its built-in character code instead.
    """
    return canonical_name in _RAW_WIDTHS and canonical_name != "zapfdingbats"
