"""Published metrics for the PDF standard 14 fonts, in 1000-unit em space.

A standard 14 font dictionary carries no /Widths array and no /FontDescriptor
-- that is what makes it a standard 14 font, since every conforming viewer is
required to already know its metrics. That leaves nothing inside the file to
check a candidate replacement against, and nothing to hang an embedded font
program on. These published widths supply both: they verify that an installed
font really is the face it claims to be, and they supply the /Widths array a
font dictionary needs once it stops relying on the viewer's built-in copy.

Values are the Adobe Core 14 AFM widths keyed by Unicode code point, stored as
a default width plus the code points that differ from it. A /Differences
encoding names glyphs rather than characters, so resolve those through
``fontTools.agl.toUnicode`` before looking a width up here. Font keys are
canonical names as produced by
:func:`~docassemble.ALDashboard.pdf_accessibility._canonical_font_name`.

ZapfDingbats is the one exception: its glyphs (``a1``, ``a2``, ...) have no
Adobe Glyph List entries, so there is no Unicode code point to key them by, and
the shipping clones cmap the face's own built-in encoding instead. That entry is
therefore keyed by built-in character code, which is exactly what those cmaps
return. :func:`is_unicode_keyed` reports which convention an entry uses.
"""

